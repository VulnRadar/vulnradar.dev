/**
 * "runtime" takes effect within the resolver cache TTL with no deploy.
 * "build" is baked into statically generated HTML, so an edit applies on the
 * next build. Both are editable by an admin; only the propagation differs.
 */
export type SettingTier = "runtime" | "build";

export type SettingType =
  "string" | "int" | "bool" | "float" | "email" | "url" | "enum";

/** One admin tab per group. The tab list is derived from these values. */
export type SettingGroup =
  | "General"
  | "Branding"
  | "SEO"
  | "Features"
  | "Billing"
  | "Rate Limits"
  | "Scanning"
  | "Authentication"
  | "AI"
  | "Demo"
  | "Advanced";

export interface SettingDefinition {
  tier: SettingTier;
  type: SettingType;
  /**
   * The shipped value. Always the imported CONFIG_ constant so the registry
   * cannot drift from config-values.ts.
   */
  default: string | number | boolean;
  group: SettingGroup;
  label: string;
  help: string;
  /** Numeric types: value bounds. String types: length bounds. */
  min?: number;
  max?: number;
  /** Allowed values for `type: "enum"`. */
  options?: readonly string[];
}

