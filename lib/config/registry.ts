// tier and describes how it may be edited. The registry drives three things:
// the resolver's fallback (lib/config/runtime-config.ts), server-side
// validation on write, and (later) the admin settings form.
//
// Adding a configurable value means adding an entry here, not a bare
// constant. Constants that must never be edited at runtime are listed in
// NEVER_CONFIGURABLE below with the reason, so a reader can see they were
// considered rather than forgotten.

