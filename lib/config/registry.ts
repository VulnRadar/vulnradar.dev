export type SettingKey = keyof typeof SETTINGS_REGISTRY;

type ValueForType<T extends SettingType> = T extends "int" | "float"
  ? number
  : T extends "bool"
    ? boolean
    : string;

/** The runtime type a resolved setting has, derived from its registry `type`. */
export type SettingValue<K extends SettingKey> = ValueForType<
  (typeof SETTINGS_REGISTRY)[K]["type"]
>;

export function isSettingKey(key: string): key is SettingKey {
  return Object.prototype.hasOwnProperty.call(SETTINGS_REGISTRY, key);
}

export function getSettingDefinition(key: SettingKey): SettingDefinition {
  return SETTINGS_REGISTRY[key];
}

const schemaCache = new Map<SettingKey, z.ZodType>();

function schemaFor(key: SettingKey): z.ZodType {
  const cached = schemaCache.get(key);
  if (cached) return cached;

  const def: SettingDefinition = SETTINGS_REGISTRY[key];
  let schema: z.ZodType;

  switch (def.type) {
    case "int": {
      let numeric = z.coerce.number().int();
      if (def.min !== undefined) numeric = numeric.min(def.min);
      if (def.max !== undefined) numeric = numeric.max(def.max);
      schema = numeric;
      break;
    }
    case "float": {
      let numeric = z.coerce.number();
      if (def.min !== undefined) numeric = numeric.min(def.min);
      if (def.max !== undefined) numeric = numeric.max(def.max);
      schema = numeric;
      break;
    }
    case "bool":
      // Not z.coerce.boolean(): it turns the string "false" into true, which
      // is exactly the mistake this validation exists to catch.
      schema = z.union([
        z.boolean(),
        z.enum(["true", "false"]).transform((v) => v === "true"),
      ]);
      break;
    case "email":
      schema = z.email();
      break;
    case "url":
      schema = z.url();
      break;
    case "enum":
      schema = z.enum([...(def.options ?? [])] as [string, ...string[]]);
      break;
    case "string": {
      let text = z.string();
      if (def.min !== undefined) text = text.min(def.min);
      if (def.max !== undefined) text = text.max(def.max);
      schema = text;
      break;
    }
  }

  schemaCache.set(key, schema);
  return schema;
}

/**
 * Validate an admin-supplied value against its registry constraints.
 *
 * On success the returned `value` is the canonical string to store, so the
 * database never holds a padded or oddly typed representation.
 */
export function validateSettingValue(
  key: SettingKey,
  value: unknown,
): { ok: true; value: string } | { ok: false; error: string } {
  const raw = typeof value === "string" ? value.trim() : value;
  const parsed = schemaFor(key).safeParse(raw);
  if (!parsed.success) {
    const def = SETTINGS_REGISTRY[key];
    const detail = parsed.error.issues[0]?.message ?? "Invalid value";
    return { ok: false, error: `${def.label} (${key}): ${detail}` };
  }
  return { ok: true, value: String(parsed.data) };
}

/**
 * Coerce a stored TEXT value (or an environment override) into the type the
 * registry declares. Returns undefined when the stored row is malformed, so
 * the caller can fall back to the shipped default instead of throwing.
 */
export function coerceSettingValue<K extends SettingKey>(
  key: K,
  raw: unknown,
): SettingValue<K> | undefined {
  const input = typeof raw === "string" ? raw.trim() : raw;
  const parsed = schemaFor(key).safeParse(input);
  return parsed.success ? (parsed.data as SettingValue<K>) : undefined;
}
