#!/usr/bin/env node
/**
 * Writes lib/i18n/messages/catalog.ts: the static import list for every
 * message file under lib/i18n/messages/<locale>/<namespace>.json.
 *
 *   node lib/i18n/build-catalog.mjs           write the file
 *   node lib/i18n/build-catalog.mjs --check   exit 1 if it is out of date
 *
 * The imports have to be static (see lib/i18n/messages.ts), so something has
 * to list the files, and a hand-kept list goes stale the first time a
 * namespace is added. Two translation changes in flight at once then also
 * conflict on that list. Regenerating it after a merge cannot conflict, and
 * tests/lib/i18n/catalog.test.ts runs the same renderer against the committed
 * file, so a stale list fails CI instead of shipping a namespace nobody loads.
 *
 * Output is already in Prettier's layout (one object entry per line, no
 * arrays), so `npm run format:check` leaves it alone.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const HERE = path.dirname(fileURLToPath(import.meta.url));

export const MESSAGES_DIR = path.join(HERE, "messages");
export const CATALOG_FILE = path.join(MESSAGES_DIR, "catalog.ts");

const NAMESPACE = /^[a-z][A-Za-z0-9]*$/;
const LOCALE = /^[a-z]{2,3}(-[A-Z]{2})?$/;

function directories(dir) {
  return readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();
}

/** "pt-BR" -> "ptBR", "footer" -> "Footer": the pieces of an import name. */
function camel(value) {
  return value.replace(/-(.)/g, (_, c) => c.toUpperCase());
}

function capitalise(value) {
  return value.charAt(0).toUpperCase() + value.slice(1);
}

/**
 * Every locale folder and the namespace files in it, as
 * `{ locale: [namespace, ...] }`, both sorted so the output is stable.
 */
export function scanMessages(dir = MESSAGES_DIR) {
  const found = {};
  for (const locale of directories(dir)) {
    if (!LOCALE.test(locale)) {
      throw new Error(`${locale} is not a locale folder name (en, pt-BR)`);
    }
    found[locale] = readdirSync(path.join(dir, locale))
      .filter((file) => file.endsWith(".json"))
      .map((file) => file.slice(0, -".json".length))
      .sort();
    for (const namespace of found[locale]) {
      if (!NAMESPACE.test(namespace)) {
        throw new Error(
          `${locale}/${namespace}.json: a namespace file is named in camelCase (nav, aiChat)`,
        );
      }
    }
  }
  return found;
}

/** The text of catalog.ts for what is on disk. */
export function renderCatalog(dir = MESSAGES_DIR) {
  const found = scanMessages(dir);
  const importName = (locale, namespace) =>
    `${camel(locale)}${capitalise(namespace)}`;
  const key = (value) =>
    /^[A-Za-z_$][\w$]*$/.test(value) ? value : `"${value}"`;

  const lines = [
    "/**",
    " * GENERATED by lib/i18n/build-catalog.mjs from the files beside this one.",
    " * Do not edit by hand. After adding, renaming or removing a namespace file:",
    " *",
    " *   node lib/i18n/build-catalog.mjs",
    " *",
    " * tests/lib/i18n/catalog.test.ts fails while this file is out of date.",
    " */",
  ];

  for (const [locale, namespaces] of Object.entries(found)) {
    for (const namespace of namespaces) {
      lines.push(
        `import ${importName(locale, namespace)} from "./${locale}/${namespace}.json";`,
      );
    }
  }

  lines.push("", "export const CATALOG = {");
  for (const [locale, namespaces] of Object.entries(found)) {
    lines.push(`  ${key(locale)}: {`);
    for (const namespace of namespaces) {
      lines.push(`    ${namespace}: ${importName(locale, namespace)},`);
    }
    lines.push("  },");
  }
  lines.push("};", "");

  return lines.join("\n");
}

function main() {
  const next = renderCatalog();
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      // A Windows checkout may have rewritten the line endings.
      current = readFileSync(CATALOG_FILE, "utf8").replace(/\r\n/g, "\n");
    } catch {
      // A missing file is as stale as a different one.
    }
    if (current !== next) {
      console.error(
        "lib/i18n/messages/catalog.ts is out of date. Run: node lib/i18n/build-catalog.mjs",
      );
      process.exit(1);
    }
    return;
  }
  writeFileSync(CATALOG_FILE, next);
}

if (
  process.argv[1] &&
  pathToFileURL(path.resolve(process.argv[1])).href === import.meta.url
) {
  main();
}
