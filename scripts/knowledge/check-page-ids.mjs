// The id space of the public /checks/<id> pages, written out so client code can
// link a finding to its fix guide without importing the check catalogue.
//
// Kept apart from compile-checks-knowledge.mjs because that script builds on
// import (it ends in a top-level `await build()`), so a test cannot load it
// without rewriting the knowledge files. Everything here is pure.
//
// A page exists for every checks-data entry except the disabled duplicates:
// that is the same filter lib/seo/checks-content.ts applies, and
// tests/lib/seo/check-page-ids.test.ts holds the two together.

const DISABLED_MARKER = "(disabled duplicate)";

/**
 * @param {Record<string, Array<{ id: string, title?: string, emittedAs?: string[] }>>} byCategory
 * @returns {{ ids: string[], asyncPageIds: Record<string, string> }}
 *   ids: every id that has a page, sorted.
 *   asyncPageIds: async check id -> the page that documents it. Several
 *   write-ups can map to one async check (two takeover pages for one finding);
 *   the first in alphabetical category order, then file order, wins, so the
 *   result is deterministic.
 */
export function collectPageIds(byCategory) {
  const ids = [];
  const asyncPageIds = {};
  for (const category of Object.keys(byCategory).sort()) {
    for (const check of byCategory[category]) {
      if (String(check.title ?? "").includes(DISABLED_MARKER)) continue;
      ids.push(check.id);
      for (const asyncId of check.emittedAs ?? []) {
        if (!(asyncId in asyncPageIds)) asyncPageIds[asyncId] = check.id;
      }
    }
  }
  ids.sort();
  const sorted = {};
  for (const key of Object.keys(asyncPageIds).sort()) {
    sorted[key] = asyncPageIds[key];
  }
  return { ids, asyncPageIds: sorted };
}

// Prettier puts a string value on its own line when `key: "value",` would pass
// 80 columns, and `format:check` runs over this file, so the layout has to be
// what Prettier would write.
function renderEntry(key, value) {
  const line = `  "${key}": "${value}",`;
  return line.length <= 80 ? line : `  "${key}":\n    "${value}",`;
}

export function renderPageIdsModule({ ids, asyncPageIds }) {
  return [
    "// AUTO-GENERATED by scripts/knowledge/compile-checks-knowledge.mjs -- do not hand-edit.",
    "// Regenerated on every `npm run build` / `npm run dev` (prebuild/predev hooks).",
    "",
    "/** Every id that has a /checks/<id> page, sorted. */",
    "export const CHECK_PAGE_IDS: readonly string[] = [",
    ...ids.map((id) => `  "${id}",`),
    "];",
    "",
    "/**",
    " * Async probe id -> the /checks page that documents it. A finding from the",
    " * async layer carries `async-<title slug>--<hash>`, which is in no page's id",
    " * space, so this is how it finds its fix guide.",
    " */",
    "export const ASYNC_CHECK_PAGE_IDS: Readonly<Record<string, string>> = {",
    ...Object.entries(asyncPageIds).map(([key, value]) =>
      renderEntry(key, value),
    ),
    "};",
    "",
  ].join("\n");
}
