#!/usr/bin/env node
// Writes app/docs/architecture/repo-dirs.generated.ts, the directory column of
// the "Where things live" table on /docs/architecture.
//
// A committed file rather than a readdir in the page, because the page cannot
// do it itself: the docs layouts read the CSP nonce, so the page renders per
// request, and the published image carries no app/, components/, tests/ or
// extension/ to list. tests/app/docs/architecture-where-things-live.test.ts
// fails when the committed list and the checkout disagree.
//
// Run: `node scripts/docs/generate-repo-dirs.mjs`

import { execFileSync } from "node:child_process";
import { existsSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");
const OUTPUT = join(
  ROOT,
  "app",
  "docs",
  "architecture",
  "repo-dirs.generated.ts",
);

/**
 * Every directory two levels deep that git tracks a file under. readdirSync
 * alone would also list node_modules, .next and whatever else a working copy
 * has lying around, and the answer has to be the same on every machine.
 */
function trackedDirs(root) {
  const dirs = new Set();
  const files = execFileSync("git", ["ls-files", "-z"], {
    cwd: root,
    encoding: "utf8",
    maxBuffer: 64 * 1024 * 1024,
  });
  for (const file of files.split("\0").filter(Boolean)) {
    const [first, second, third] = file.split("/");
    if (second !== undefined) dirs.add(first);
    if (third !== undefined) dirs.add(`${first}/${second}`);
  }
  return dirs;
}

function subdirectories(root, rel, tracked) {
  return readdirSync(join(root, rel), { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .filter((name) => tracked.has(rel ? `${rel}/${name}` : name))
    .sort();
}

export function listRepoDirs(root = ROOT) {
  const tracked = trackedDirs(root);
  return {
    top: subdirectories(root, "", tracked),
    lib: subdirectories(root, "lib", tracked),
    components: subdirectories(root, "components", tracked),
  };
}

function render({ top, lib, components }) {
  const list = (names) => names.map((name) => `    "${name}",\n`).join("");
  return (
    "// Generated by scripts/docs/generate-repo-dirs.mjs. Do not edit by hand.\n" +
    "export const REPO_DIRS = {\n" +
    `  top: [\n${list(top)}  ],\n` +
    `  lib: [\n${list(lib)}  ],\n` +
    `  components: [\n${list(components)}  ],\n` +
    "} as const;\n"
  );
}

const isMain =
  process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;

// Without .git there is nothing to ask what is tracked, and a Docker build
// context is missing directories on purpose, so the committed list stands.
if (isMain && existsSync(join(ROOT, ".git"))) {
  writeFileSync(OUTPUT, render(listRepoDirs()));
}
